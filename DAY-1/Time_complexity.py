#Time complexity
#Time complexity is a way of describing how the number of operations performed by an 
#algorithm grows as the input size increases.
#Big O Notation
#we use big o notation to descibe the growth of an algorithm
#o(1)-constant time[does not depend on n]
#o(1) means the amount of work doesn't depend on how large the input is

#o(log n)-Logarithmic[very slow growth]
#if an algorithm repeatedly divides the problem by 2it is often o(log n)

#o(n)-Linear time
#one loop through all n elements.The amount of work grows directly with input size

#o(n*2)-Quadratic time
#Two nested loops.The amount of work grows approximately as the square the input size,commonly due to nested loops

#o(n*3)-Three nested loops
#The amount of work grows approximately as the cube of input size,commonly due to 3 nested loops

#o(n logn)-Loglinear[lineararithmic time]
#The algorithm performs work proportional to n across logarithmic levels

#o(2*n)-Exponential time
#The amount of work grows exponentially,approximately doubling when the input size increases by one

#o(n!)-Factorial time
#The amount of work grows according to the factorial of the input size and becomes extremly large very quickly

